/**
 * Test punkt-w-wielokącie (ray casting). Zwraca true, gdy punkt leży wewnątrz
 * granic gminy Jejkowice. Tani obliczeniowo — jeden przebieg po wierzchołkach.
 */
export function isInsideJejkowice(lng: number, lat: number): boolean {
  const poly = JEJKOWICE_BOUNDARY
  let inside = false
  for (let i = 0, j = poly.length - 1; i < poly.length; j = i++) {
    const [xi, yi] = poly[i]
    const [xj, yj] = poly[j]
    const intersect =
      yi > lat !== yj > lat &&
      lng < ((xj - xi) * (lat - yi)) / (yj - yi) + xi
    if (intersect) inside = !inside
  }
  return inside
}
